import bcrypt from "bcryptjs";

// Node-runtime only (bcrypt is not edge-compatible) -- only import this
// from route handlers, never from middleware.ts.

export async function hashPassword(password: string): Promise<string> {
  return bcrypt.hash(password, 10);
}

export async function verifyPassword(password: string, hash: string): Promise<boolean> {
  return bcrypt.compare(password, hash);
}

// Used when the team creates a client portal login and we generate a
// temporary password for them to hand off, rather than the client
// self-registering.
export function generateTempPassword(): string {
  const chars = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789";
  let out = "";
  for (let i = 0; i < 12; i++) {
    out += chars[Math.floor(Math.random() * chars.length)];
  }
  return out;
}
